"""全部可调阈值的唯一来源。

设计约束（用户明确要求）：**业务代码零硬编码**。
`services/` 下任何模块都不得出现魔法数字，一律从这里导入。
这样做的直接收益是调阈值不必读懂算法——答辩前想让宠物更敏感，改一个数即可。

常量按所属层次分组：
    §1 时间与窗口      —— 前瞻 / 回顾窗口，决定了"看多远"和"回溯多久"
    §2 冲突检测        —— 三类冲突的判定阈值
    §3 信号聚合        —— 拖延指数等派生指标的公式参数
    §4 宠物六档状态机  —— 情绪判定阈值与能量公式
    §5 LLM 编排与干预  —— 触发、节奏、缓存、降权
"""

from __future__ import annotations

from datetime import timedelta

# ==================================================================
# §1 时间与窗口
# ==================================================================

#: 前瞻窗口：只关心这个时间范围内将发生的事（文档 B13，今天 + 未来 24h）
FORWARD_WINDOW = timedelta(hours=24)

#: 回顾窗口：统计类指标回溯多少天
LOOKBACK_WINDOW = timedelta(days=7)

#: 一天的时间窗 [08:00, 23:00)。凌晨的空白不该被当作「你可以休息」，
#: 这条取舍沿用自旧版 find_gaps 的注释，八年的产品直觉，别改。
DAY_WINDOW_START_HOUR = 8
DAY_WINDOW_END_HOUR = 23

#: 一天内的可用时长（分钟）。用于**空档识别**，不用于负载判定。
DAY_AVAILABLE_MINUTES = (DAY_WINDOW_END_HOUR - DAY_WINDOW_START_HOUR) * 60

#: 单日计划承载上限（分钟）= 10 小时。这是 `overload` 的**分母**。
#:
#: ⚠️ 为什么不用上面的 DAY_AVAILABLE_MINUTES：如果负载的分子也被裁到同一个窗口内，
#: 比率的上限就是 1.0，`CONFLICT_OVERLOAD_RATIO = 1.2` 这条阈值将**永远无法触发**，
#: 变成死代码。这里刻意让分子（整天内实际排掉的时间）与分母（合理承载量）不同源：
#: 超过 1.2 × 10h = 12 小时才算「今天塞太满」，这是一个既可达又不误报的量。
#: 旧版 Tkinter 用的判定是「连续占满 ≥4 小时且 ≥4 条」，比这里宽松得多；
#: 但那时宠物一天只提醒一次，而现在这个比率还要喂给 LLM 做决策输入，
#: 过于敏感的阈值会让模型频繁收到"用户很忙"的假信号。
PLANNED_CAPACITY_MINUTES = 10 * 60

# ==================================================================
# §2 冲突检测
# ==================================================================

#: 软冲突阈值：两条日程之间的间隔小于该分钟数即报 no_buffer（文档 B1）
CONFLICT_BUFFER_MINUTES = 10

#: 负载比阈值：计划时长 / 可用时长 超过该值即报 overload（文档 B2）
CONFLICT_OVERLOAD_RATIO = 1.2

#: 触发 overload 还需要的最小日程条数，避免"只有 1 条超长任务"被误判为塞太满。
#: 沿用旧版 PET_BUSY_MIN_COUNT 的思路。
CONFLICT_OVERLOAD_MIN_COUNT = 4

#: 空档识别的最短时长（分钟），短于此不值得提醒休息
IDLE_BLOCK_MIN_MINUTES = 30

#: 不参与冲突检测的状态。已完成 / 已放弃的计划不再占用未来时间。
CONFLICT_EXCLUDED_STATUSES = frozenset({"done", "dropped"})

#: hard 冲突类型集合。hard=物理上不可能共存，必须由 LLM 或规则重排；
#: soft 冲突只是"不理想"，模型可以选择不处理。
CONFLICT_HARD_KINDS = frozenset({"overlap"})

# ==================================================================
# §3 信号聚合
# ==================================================================

#: 拖延指数归一化系数（文档 B9）。当全部任务逾期且平均逾期 7 天时取 1.0。
PROCRASTINATION_SCALE = 7.0

#: 完成率的默认分母保护：近 7 天没有任何应完成任务时不该判定为 0%，
#: 此时返回一个中性值而不是惩罚用户。
EMPTY_COMPLETION_RATE = 0.5

#: 逾期天数的最大计入值，防止一条拖了半年的任务把平均值拉爆
MAX_OVERDUE_DAYS = 30.0

# ==================================================================
# §4 宠物六档状态机
# ==================================================================

#: 判定优先级，必须严格按此顺序短路（用户裁决）。
#: 同一份输入永远必须得到同一份输出——这是"情绪是仪表盘"的底线。
PET_MOOD_PRIORITY: tuple[str, ...] = (
    "alert",    # 1 前瞻预警：未来 24h 存在 hard 冲突
    "dormant",  # 2 长期停摆：连续多日无任何完成
    "tired",    # 3 已在拖延：连续多日存在逾期未处理
    "guilty",   # 4 拖欠累积：拖延指数高且完成率低
    "great",    # 5 状态很好：完成率高且连续达标
    "normal",   # 6 兜底
)

#: 2 · dormant —— 连续多少天没有任何 task_completed 事件
PET_DORMANT_IDLE_DAYS = 3

#: 3 · tired —— 连续多少天存在逾期未完成且未处理的任务
PET_TIRED_OVERDUE_DAYS = 2

#: 4 · guilty —— 拖延指数下限
PET_GUILTY_INDEX_MIN = 0.6

#: 4 · guilty —— 7 日完成率上限（低于该值才算差）
PET_GUILTY_COMPLETION_MAX = 0.5

#: 5 · great —— 当日完成率下限
PET_GREAT_COMPLETION_MIN = 0.8

#: 5 · great —— 连续达标天数下限
PET_GREAT_STREAK_MIN = 3

#: energy 公式权重（文档 B11）
ENERGY_COMPLETION_WEIGHT = 0.6
ENERGY_PROCRASTINATION_WEIGHT = 0.4

# ==================================================================
# §5 LLM 编排与干预
# ==================================================================

#: 拖延指数达到该值时认为需要 LLM 介入（文档 B3）
LLM_TRIGGER_INDEX = 0.5

#: ------------------------------------------------------------------
#: 干预节奏三参数（文档 B4 / B5 / B6）—— P5 节奏闸门的**唯一**取值来源。
#:
#: 这三个数不是性能参数，而是产品伦理参数：它们决定"系统多久可以打扰用户一次"。
#: 定得不当时最坏的结果不是慢，而是用户把整个应用关掉。
#: 业务代码（services/rhythm.py）不得出现任何字面量，一律从这里导入，
#: 答辩现场想调"它是不是太烦了"，改这三个数即可，不必读懂闸门算法。
#: ------------------------------------------------------------------

#: B4 · 冷却期（分钟）：距上一次**送达**干预不足此时长，自动触发一律不发。
#: 45 分钟的来源是"一次专注块的量级"——短于它会把用户的整段工作切成碎片。
INTERVENTION_COOLDOWN_MINUTES = 45

#: B5 · 每日上限（条）：本地一天内自动送达的干预条数上限。
#: 3 条是刻意的克制：超过这个数，助手就从"提醒"变成"监工"。
INTERVENTION_DAILY_LIMIT = 3

#: B6 · 降权阈值（次）：同一 decision_type 被忽略（snooze/mute）累计达此数后彻底降权。
#: 降权的含义是双重的：既进闸门的黑名单，也进 prompt 的负面清单（反馈回流）。
INTERVENTION_MUTE_THRESHOLD = 3

#: 反馈历史回溯窗口（天）。统计"被忽略几次"只看这段时间内的干预 ——
#: 三个月前点过一次"稍后"，不该让今天的助手闭嘴。
INTERVENTION_FEEDBACK_WINDOW_DAYS = 7

#: 闸门读取的最近干预条数上限。纯防御：单用户场景下实际远小于此。
INTERVENTION_HISTORY_LIMIT = 200

#: 绕过节奏闸门的触发类型。**只有这一个**，且它必须来自用户的显式动作。
#: 用户主动点"问决策器"时不该被自己的助手以"额度用完了"为由拒绝 ——
#: 那是在惩罚用户使用它。但手动触发仍会刷新冷却时钟（见 rhythm.py），
#: 所以点一次不会引来一串自动干预。
RHYTHM_BYPASS_TRIGGERS = frozenset({"manual"})

#: 计入"已忽略"的反馈类型。
#: `accept` 显然不算；`snooze`（稍后）与 `mute`（别再提）都表达了"现在不想被打扰"，
#: 因此都计入降权计数 —— 这正是"忽略三次就闭嘴"的字面含义。
RHYTHM_IGNORE_FEEDBACKS = frozenset({"snooze", "mute"})

#: LLM 结果缓存 TTL（分钟，文档 B7）
LLM_CACHE_TTL_MINUTES = 30

#: 决策契约版本号，写入 DecisionPayload.schema_version。
#: 升级契约时先改这个数，才能让"录制的旧 fixture"被识别出来而不是被误当新版本回放。
DECISION_SCHEMA_VERSION = "1.0"

#: 单次决策最多给几条建议（喂给模型的 constraints.max_suggestions）。
#: 定 3 而不是 5：干预是打扰，一次甩五条建议等于没有建议。
DECISION_MAX_SUGGESTIONS = 3

#: 干预卡片的有效期（分钟）。过期后前端不再展示 —— 一份基于 20 分钟前
#: 数据的重排建议，现在多半已经不适用了。
INTERVENTION_TTL_MINUTES = 60

#: 交给模型的最长文本长度，与 §4.3 契约的 maxLength 一一对应。
#: 超长一律**截断**而不是判失败（校验 10）：模型啰嗦是风格问题，不是错误。
DECISION_SUMMARY_MAX_LEN = 120
DECISION_RATIONALE_MAX_LEN = 200
DECISION_TITLE_MAX_LEN = 40
DECISION_MESSAGE_MAX_LEN = 300
DECISION_PET_LINE_MAX_LEN = 80

#: 模型单次决策的失败重试次数（校验 1–3 失败时）。
#: 第 2 次会把 Pydantic 的校验错误原文回传，模型通常一次就改对。
LLM_MAX_RETRIES = 2

#: 因 `finish_reason == "length"` 被截断（**或 content 全空**）时，逐档抬高的 token 上限。
#:
#: 这两件事是同一个病：实测"空 content"的 `completion_tokens == max_tokens`、
#: `reasoning_tokens == max_tokens` —— 模型把额度全烧在推理上，一个输出 token 都没剩。
#: 所以空响应**不能**按"偶发故障直接降级"处理，那样等于用同样的额度再撞一次墙；
#: 它必须和截断走同一条抬档路径（见 docs/09）。
#:
#: 只抬两档是有意的：抬到 8192 还撞顶，说明问题不在额度而在 prompt 本身该裁剪了
#: （记录条数 / 事件条数），继续加只是把延迟和成本推高。
LLM_TOKEN_LADDER: tuple[int, ...] = (4096, 8192)

#: 送入 prompt 的记录条数上限（2026-10-30 由 40 收紧到 14）。
#: 实测推理 token 随记录条数线性膨胀：9 条要 905~2737，40 条几乎必然撞顶
#: 8192 的抬档上限（docs/09 §6 有前后对比）。14 = 满 12 小时日程的典型条数，
#: 留有 2 条余量；配合 `_rank_records` 的相关度排序，截掉的只是与本次决策
#: 无关的远期条目。第一刀只动条数；若仍撞顶，下一刀是去掉 tags 等低信息字段。
LLM_PROMPT_MAX_RECORDS = 14

#: 送入 prompt 的行为事件条数上限。事件比记录轻（无标题正文），暂不收紧。
LLM_PROMPT_MAX_EVENTS = 30

#: 可工作时间窗（本地时间）。模型给的建议不得落在这个区间之外（校验 6）。
#: 与 DAY_WINDOW_* 同源：夜里的空档不是"可以安排"的时段。
WORKING_HOURS_START = "08:00"
WORKING_HOURS_END = "23:00"

#: 规则降级引擎：顺延时的最小步进（分钟）与最多搜多少个候选落点。
#: 步进取 15 是因为日程表上的时间基本都是整刻/整半点，
#: 生成 "10:07" 这种时间只会让人怀疑系统坏了。
FALLBACK_SLOT_STEP_MINUTES = 15
FALLBACK_MAX_CANDIDATES = 96  # 24h / 15min

#: L3 降级阈值：模型说"不用干预"，但拖延指数高到这个值时后端仍发一条规则提醒。
#: 这不是不信任模型，而是承认一件事：**模型看不到"用户已经三天没动"的重量**，
#: 它只看得见当前这段对话。信号足够强时，后端保留最终发言权。
LLM_L3_INDEX = 0.8

#: 规则降级方案的置信度。
#: 定 0.5 而不是更高：它是"能用"的方案不是"最优"的方案，
#: 标高了会让人误以为模型也这么想。
FALLBACK_CONFIDENCE = 0.5

#: 规则降级引擎：一条日程最多被往后推多少天。
#: 拖到下周的"重排建议"没有意义，超过这个跨度就转为 nudge（只提醒、不自动排）。
FALLBACK_MAX_MOVE_DAYS = 3

# ==================================================================
# §6 实时通道（P3-b）
# ==================================================================

#: SSE 心跳间隔（秒）。短于此值发一次注释帧，防止中间代理因空闲掐断连接。
SSE_HEARTBEAT_SEC = 15

#: 断连检测周期（秒）。**必须远小于心跳间隔**。
#: 队列的阻塞读会把 `request.is_disconnected()` 的检查推迟到超时之后，
